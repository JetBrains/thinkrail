import {
	existsSync,
	mkdtempSync,
	readdirSync,
	readFileSync,
	rmSync,
	statSync,
	writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { SHARED_MODULE_EXPORTS } from "@thinkrail/extension-api/installed";
import { EXTENSION_API_VERSION } from "../src/shared";
import { buildSdk } from "./build";

export const SNAPSHOT_DIR = fileURLToPath(new URL("../api/", import.meta.url));

export function snapshotFile(api: string): string {
	return join(SNAPSHOT_DIR, `${api}.api.md`);
}

function declarationFiles(dir: string): string[] {
	return readdirSync(dir).flatMap((name) => {
		const path = join(dir, name);
		if (statSync(path).isDirectory()) return declarationFiles(path);
		return path.endsWith(".d.ts") ? [path] : [];
	});
}

export function renderSnapshot(api: string, dist: string): string {
	const sections = declarationFiles(dist)
		.map(
			(path) => [relative(dist, path).replaceAll("\\", "/"), readFileSync(path, "utf8")] as const,
		)
		.sort(([a], [b]) => (a < b ? -1 : 1))
		.map(([path, code]) => `### \`${path}\`\n\n\`\`\`ts\n${code.trimEnd()}\n\`\`\``);
	return [
		`# Extension API ${api} — the frozen surface`,
		"",
		"Generated by `bun run api:snapshot` in `packages/extension-sdk` from the allow-list",
		"(`SHARED_MODULE_EXPORTS` in `@thinkrail/extension-api/installed`) and the SDK's generated",
		"declarations. Extensions are built against this file: it is never edited to match the code",
		"(`packages/extension-sdk/SPEC.md` § Frozen API snapshots).",
		"",
		"## Runtime exports",
		"",
		"```json",
		JSON.stringify(SHARED_MODULE_EXPORTS, null, "\t"),
		"```",
		"",
		"## Declarations",
		"",
		...sections.flatMap((section) => [section, ""]),
	].join("\n");
}

export async function currentSnapshot(): Promise<string> {
	const dist = mkdtempSync(join(tmpdir(), "thinkrail-extension-sdk-api-"));
	try {
		await buildSdk(dist);
		return renderSnapshot(EXTENSION_API_VERSION, dist);
	} finally {
		rmSync(dist, { recursive: true, force: true });
	}
}

export function snapshotExports(markdown: string): Record<string, string[]> {
	const json = /## Runtime exports\n\n```json\n([\s\S]*?)\n```/.exec(markdown)?.[1];
	if (json === undefined) throw new Error("the snapshot has no runtime exports block");
	return JSON.parse(json) as Record<string, string[]>;
}

const DECLARED =
	/^export (?:declare )?(?:function|const|let|class|interface|type|enum) ([A-Za-z_$][\w$]*)/gm;
const LISTED = /^export (?:type )?\{([^}]*)\}/gm;

export function snapshotDeclarations(markdown: string): Record<string, string[]> {
	const declared: Record<string, string[]> = {};
	for (const match of markdown.matchAll(/### `([^`]+)`\n\n```ts\n([\s\S]*?)\n```/g)) {
		const [, file = "", code = ""] = match;
		const names = new Set([...code.matchAll(DECLARED)].map((found) => found[1] ?? ""));
		for (const list of code.matchAll(LISTED)) {
			for (const item of (list[1] ?? "").split(",")) {
				const name = item
					.trim()
					.replace(/^type /, "")
					.split(/\s+as\s+/)
					.at(-1)
					?.trim();
				if (name) names.add(name);
			}
		}
		declared[file] = [...names].sort();
	}
	return declared;
}

export function lostSince(earlier: string, current: string): string[] {
	const lost: string[] = [];
	const exportsNow = snapshotExports(current);
	for (const [specifier, names] of Object.entries(snapshotExports(earlier))) {
		for (const name of names)
			if (!exportsNow[specifier]?.includes(name)) lost.push(`${specifier}: ${name}`);
	}
	const declaredNow = snapshotDeclarations(current);
	for (const [file, names] of Object.entries(snapshotDeclarations(earlier))) {
		if (file.includes("/chunks/")) continue;
		for (const name of names) if (!declaredNow[file]?.includes(name)) lost.push(`${file}: ${name}`);
	}
	return lost;
}

export function firstDifference(expected: string, actual: string): string {
	const want = expected.split("\n");
	const got = actual.split("\n");
	const line = want.findIndex((text, index) => text !== got[index]);
	const at = line === -1 ? want.length : line;
	return [
		`first difference at line ${at + 1}:`,
		`  snapshot: ${want[at] ?? "(end of file)"}`,
		`  current:  ${got[at] ?? "(end of file)"}`,
	].join("\n");
}

export function driftMessage(api: string, detail: string): string {
	const [major, minor] = api.split(".").map(Number);
	const file = `packages/extension-sdk/api/${api}.api.md`;
	return [
		`Extension API ${api} no longer matches its frozen snapshot, ${file}.`,
		"Extensions are built against that snapshot, so it is not edited to match the code:",
		`- A removed or changed name or type breaks every extension built for ${major}.x. Undo it, or make it extension API ${(major ?? 0) + 1}.0: set EXTENSION_API_VERSION to "${(major ?? 0) + 1}.0" in packages/extension-api/src/manifest.ts and packages/extension-sdk/src/shared.ts and write the new snapshot.`,
		`- An addition only is extension API ${major}.${(minor ?? 0) + 1}: set EXTENSION_API_VERSION to "${major}.${(minor ?? 0) + 1}" in both files and write api/${major}.${(minor ?? 0) + 1}.api.md with \`bun run api:snapshot\` in packages/extension-sdk; ${api}'s snapshot stays as it is.`,
		"- Only while this API version is unreleased (the SDK is still 0.0.0), or when a toolchain upgrade merely reprinted identical declarations, may `bun run api:snapshot --rewrite` replace it.",
		"",
		detail,
	].join("\n");
}

if (import.meta.main) {
	const current = await currentSnapshot();
	const target = snapshotFile(EXTENSION_API_VERSION);
	if (process.argv.includes("--print")) {
		process.stdout.write(current);
	} else if (existsSync(target) && !process.argv.includes("--rewrite")) {
		const committed = readFileSync(target, "utf8");
		if (committed === current) {
			console.log(`${relative(process.cwd(), target)} is current.`);
		} else {
			console.error(driftMessage(EXTENSION_API_VERSION, firstDifference(committed, current)));
			process.exit(1);
		}
	} else {
		writeFileSync(target, current);
		console.log(`wrote ${relative(process.cwd(), target)}`);
	}
}
