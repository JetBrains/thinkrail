import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { components, guides } from "../content";
import type { ComponentDoc, GuidePage, PropDoc } from "../content/types";

const LIBRARY = fileURLToPath(new URL("..", import.meta.url));
export const TARGET = fileURLToPath(
	new URL("../../../../packages/ui/COMPONENTS.md", import.meta.url),
);

const cell = (text: string) => text.replaceAll("|", "\\|").replaceAll("\n", " ");
const table = (head: readonly string[], rows: readonly (readonly string[])[]) =>
	[
		`| ${head.join(" | ")} |`,
		`| ${head.map(() => "---").join(" | ")} |`,
		...rows.map((row) => `| ${row.map(cell).join(" | ")} |`),
	].join("\n");
const code = (text: string) => `\`${text}\``;
const list = (items: readonly string[]) => items.map((item) => `- ${item}`).join("\n");

function exampleSource(doc: ComponentDoc, id: string): string {
	return readFileSync(join(LIBRARY, "examples", doc.slug, `${id}.tsx`), "utf8").trimEnd();
}

function propsTable(props: Readonly<Record<string, PropDoc>>): string {
	return table(
		["Prop", "Type", "Default", "Description"],
		Object.entries(props).map(([name, prop]) => [
			code(name),
			code(prop.type),
			prop.default ? code(prop.default) : "—",
			prop.description,
		]),
	);
}

function guide(page: GuidePage): string {
	return [
		`## ${page.title}`,
		page.summary,
		...page.sections.flatMap((section) => [
			`### ${section.title}`,
			section.body,
			...(section.rules
				? [list(section.rules.map((rule) => `**${rule.id}** — ${rule.text}`))]
				: []),
		]),
	].join("\n\n");
}

function component(doc: ComponentDoc): string {
	return [
		`## ${doc.name}`,
		doc.summary,
		`\`\`\`tsx\n${doc.importLine}\n\`\`\``,
		"### When to use",
		list(doc.whenToUse),
		"### Alternatives",
		table(
			["Instead", "When"],
			doc.alternatives.map((alt) => [alt.name, alt.when]),
		),
		"### Anatomy",
		table(
			["Part", "Description"],
			doc.anatomy.map((part) => [part.part, part.description]),
		),
		"### Props",
		propsTable(doc.props),
		"Native button props:",
		propsTable(doc.nativeProps),
		"### Variants",
		table(
			["Variant", "Use it for"],
			Object.entries(doc.variants).map(([name, text]) => [code(name), text]),
		),
		"### Sizes",
		table(
			["Size", "Use it for"],
			Object.entries(doc.sizes).map(([name, text]) => [code(name), text]),
		),
		"### Tone",
		"`tone` applies to `outline` and `ghost`; other variants ignore it.",
		table(
			["Tone", "Use it for"],
			Object.entries(doc.tones).map(([name, text]) => [code(name), text]),
		),
		"### States",
		table(
			["State", "How", "Appearance"],
			doc.states.map((state) => [state.state, state.how, state.appearance]),
		),
		"### Accessibility",
		list(doc.accessibility),
		table(
			["Keys", "Action"],
			doc.keyboard.map((entry) => [code(entry.keys), entry.action]),
		),
		"### Usage rules",
		list(doc.rules.map((rule) => `**${rule.id}** — ${rule.text}`)),
		"### Examples",
		...doc.examples.map(
			(example) =>
				`#### ${example.title}\n\n${example.description}\n\n\`\`\`tsx\n${exampleSource(doc, example.id)}\n\`\`\``,
		),
		"### In production",
		table(
			["File", "What it shows"],
			doc.usages.map((usage) => [code(usage.file), usage.note]),
		),
		`The full technical contract is ${code(doc.spec)}.`,
	].join("\n\n");
}

export function renderMarkdown(): string {
	return `${[
		"<!-- GENERATED by apps/web/library/scripts/generate-md.ts from apps/web/library/content and apps/web/library/examples. Do not edit; run `bun run library:md`. -->",
		"# ThinkRail components",
		"The written reference of the component library. The live library renders the same content with the production components, styles and themes: `bun run library:dev`, or `bun run library:build` for the static site.",
		...guides.map(guide),
		...components.map(component),
	].join("\n\n")}\n`;
}

if (import.meta.main) {
	const next = renderMarkdown();
	if (process.argv.includes("--check")) {
		const current = readFileSync(TARGET, "utf8");
		if (current !== next) {
			console.error("packages/ui/COMPONENTS.md is stale — run `bun run library:md`.");
			process.exit(1);
		}
		console.log("library: COMPONENTS.md is up to date");
	} else {
		writeFileSync(TARGET, next);
		console.log("library: wrote packages/ui/COMPONENTS.md");
	}
}
