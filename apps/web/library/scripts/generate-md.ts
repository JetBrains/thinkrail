import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import type { Colors } from "../../scripts/colorsModel";
import { allStyles, styleClassName, type Typography } from "../../scripts/typographyModel";
import { components, docs } from "../content";
import type { ComponentDoc, DocPage, PropDoc } from "../content/types";
import { isLiveBlock, LIVE_BLOCKS, LIVE_LINE, type LiveBlock } from "../live/names";
import { radiusSteps } from "../live/tokens";

const LIBRARY = fileURLToPath(new URL("..", import.meta.url));
const REPO = join(LIBRARY, "..", "..", "..");
const COMMAND = "`bun run library:md`";
const SITE = "`bun run library:dev`";
const COMPONENTS_PATH = "packages/ui/COMPONENTS.md";
const DESIGN_PATH = "DESIGN.md";

const read = (path: string) => readFileSync(join(REPO, path), "utf8");
const readJson = <T>(path: string) => JSON.parse(read(path)) as T;
export const contentPath = (file: string) => `apps/web/library/content/${file}`;
export const content = (file: string) => read(contentPath(file)).trimEnd();

const cell = (text: string) => text.replaceAll("|", "\\|").replaceAll("\n", " ");
const table = (head: readonly string[], rows: readonly (readonly string[])[]) =>
	[
		`| ${head.join(" | ")} |`,
		`| ${head.map(() => "---").join(" | ")} |`,
		...rows.map((row) => `| ${row.map(cell).join(" | ")} |`),
	].join("\n");
const code = (text: string) => `\`${text}\``;
const list = (items: readonly string[]) => items.map((item) => `- ${item}`).join("\n");
const banner = (sources: string) =>
	`<!-- GENERATED by apps/web/library/scripts/generate-md.ts from ${sources}. Do not edit; run ${COMMAND}. -->`;

function pageTarget(slug: string): string | null {
	const page = docs.find((entry) => entry.slug === slug);
	if (page) return page.output?.path ?? contentPath(page.file);
	return components.some((doc) => doc.slug === slug) ? COMPONENTS_PATH : null;
}

export function unknownLinks(markdown: string): string[] {
	return [...markdown.matchAll(/\]\(#\/([a-z0-9-]+)\)/g)]
		.map((match) => match[1] ?? "")
		.filter((slug) => pageTarget(slug) === null);
}

const typography = () => readJson<Typography>("apps/web/src/styles/typography.json");

const NAMED_BLOCKS: Partial<Record<LiveBlock, () => string>> = {
	"type-styles": () => {
		const t = typography();
		return table(
			["Source id", "Class", "Alias of"],
			allStyles(t)
				.filter((entry) => !entry.prose)
				.map((entry) => [
					code(entry.id),
					code(`.${styleClassName(t, entry.group, entry.name)}`),
					entry.ref ? code(entry.ref) : "—",
				]),
		);
	},
};

function portable(markdown: string, from: string): string {
	const linked = markdown
		.replace(/\]\(#\/([a-z0-9-]+)\)/g, (whole, slug: string) => {
			const target = pageTarget(slug);
			return target ? `](${relative(dirname(from), target) || target})` : whole;
		})
		.replace(/\]\(\/([^)]+)\)/g, (_, path: string) => `](${relative(dirname(from), path)})`);
	return linked
		.split("\n")
		.map((line) => {
			const name = LIVE_LINE.exec(line)?.[1];
			if (!name) return line;
			const what = isLiveBlock(name) ? LIVE_BLOCKS[name] : name;
			const pointer = `> **Live in the library:** ${what}. Run ${SITE} to see the current values.`;
			const names = isLiveBlock(name) ? NAMED_BLOCKS[name] : undefined;
			return names ? `${pointer}\n\n${names()}` : pointer;
		})
		.join("\n");
}

function exampleSource(doc: ComponentDoc, id: string): string {
	return readFileSync(join(LIBRARY, "examples", doc.slug, `${id}.tsx`), "utf8").trimEnd();
}

function propsTable(props: Readonly<Record<string, PropDoc>>): string {
	return table(
		["Prop", "Type", "Default", "Description"],
		Object.entries(props).map(([name, prop]) => [
			code(name),
			code(prop.type),
			prop.default ? code(prop.default) : "—",
			prop.description,
		]),
	);
}

function component(doc: ComponentDoc): string {
	return [
		`## ${doc.name}`,
		doc.summary,
		`\`\`\`tsx\n${doc.importLine}\n\`\`\``,
		"### When to use",
		list(doc.whenToUse),
		"### Alternatives",
		table(
			["Instead", "When"],
			doc.alternatives.map((alt) => [alt.name, alt.when]),
		),
		"### Anatomy",
		table(
			["Part", "Description"],
			doc.anatomy.map((part) => [part.part, part.description]),
		),
		"### Props",
		propsTable(doc.props),
		"Native button props:",
		propsTable(doc.nativeProps),
		"### Variants",
		table(
			["Variant", "Use it for"],
			Object.entries(doc.variants).map(([name, text]) => [code(name), text]),
		),
		"### Sizes",
		table(
			["Size", "Use it for"],
			Object.entries(doc.sizes).map(([name, text]) => [code(name), text]),
		),
		"### Tone",
		"`tone` applies to `outline` and `ghost`; other variants ignore it.",
		table(
			["Tone", "Use it for"],
			Object.entries(doc.tones).map(([name, text]) => [code(name), text]),
		),
		"### States",
		table(
			["State", "How", "Appearance"],
			doc.states.map((state) => [state.state, state.how, state.appearance]),
		),
		"### Accessibility",
		list(doc.accessibility),
		table(
			["Keys", "Action"],
			doc.keyboard.map((entry) => [code(entry.keys), entry.action]),
		),
		"### Usage rules",
		list(doc.rules.map((rule) => `**${rule.id}** — ${rule.text}`)),
		"### Examples",
		...doc.examples.map(
			(example) =>
				`#### ${example.title}\n\n${example.description}\n\n\`\`\`tsx\n${exampleSource(doc, example.id)}\n\`\`\``,
		),
		"### In production",
		table(
			["File", "What it shows"],
			doc.usages.map((usage) => [code(usage.file), usage.note]),
		),
	].join("\n\n");
}

function shiftHeadings(markdown: string, by: number): string {
	let fenced = false;
	return markdown
		.split("\n")
		.map((line) => {
			if (line.startsWith("```")) fenced = !fenced;
			return !fenced && /^#{1,5} /.test(line) ? `${"#".repeat(by)}${line}` : line;
		})
		.join("\n");
}

function componentsMarkdown(): string {
	const guides = docs.filter((page) => page.area === "guides" && page.slug === "using");
	const contracts = [...new Set(components.map((doc) => doc.contract))];
	const body = [
		banner("apps/web/library/content and apps/web/library/examples"),
		"# ThinkRail components",
		`The written reference of the component library. The live library renders the same content with the production components, styles and themes: ${SITE}, or \`bun run library:build\` for the static site.`,
		...guides.map((page) => `## ${page.title}\n\n${shiftHeadings(content(page.file), 1)}`),
		...components.map(component),
		...contracts.map((file) => `## Button system contract\n\n${shiftHeadings(content(file), 1)}`),
	].join("\n\n");
	return `${portable(body, COMPONENTS_PATH)}\n`;
}

function pageMarkdown(page: DocPage & { output: NonNullable<DocPage["output"]> }): string {
	const frontmatter = page.output.frontmatter ? `---\n${page.output.frontmatter}\n---\n\n` : "";
	const sources = [contentPath(page.file), ...page.sources].join(", ");
	const body = [
		banner(sources),
		`# ${page.output.heading}`,
		`> The live page renders this text with the current values: ${SITE} → **${page.title}**.`,
		content(page.file),
	].join("\n\n");
	return `${frontmatter}${portable(body, page.output.path)}\n`;
}

interface Manifest {
	id: string;
	label: string;
	order: number;
	appearance: string;
	contrast: string;
	colors: Record<string, string | null>;
}

function designMarkdown(): string {
	const t = typography();
	const colors = readJson<Colors>("apps/web/src/styles/colors.json");
	const spacing = readJson<{ steps: Record<string, string> }>("apps/web/src/styles/spacing.json");
	const themesDir = "apps/web/src/themes/bundled";
	const manifests = readdirSync(join(REPO, themesDir))
		.filter((file) => file.endsWith(".theme.json"))
		.map((file) => readJson<Manifest>(`${themesDir}/${file}`))
		.sort((a, b) => a.order - b.order);
	const families = Object.entries(t.fontFamilies).filter(
		(entry): entry is [string, Exclude<(typeof entry)[1], { $ref: string }>] =>
			!("$ref" in entry[1]),
	);
	const styles = allStyles(t).filter((entry) => !entry.prose);
	const prompt = docs.find((page) => page.slug === "design-prompt");
	const foundations = docs.filter((page) => page.area === "foundations");
	const body = [
		banner(
			"apps/web/library/content, apps/web/src/styles/*.json, apps/web/src/styles/tokens.css and apps/web/src/themes/bundled",
		),
		"# ThinkRail design",
		...(prompt ? [content(prompt.file)] : []),
		`## Current foundations\n\nGenerated from the sources the app is built from. The full system — rules, live tokens and real components — is the component library (${SITE}); its written form is ${foundations
			.map((page) => `[${page.title}](${page.output?.path ?? contentPath(page.file)})`)
			.join(", ")} and [components](${COMPONENTS_PATH}).`,
		"### Themes",
		table(
			["Theme", "Appearance", "Contrast", "Accent", "Background", "Elevated", "Text", "Muted"],
			manifests.map((theme) => [
				`${theme.label} (${code(theme.id)})`,
				theme.appearance,
				theme.contrast,
				...["accent", "background", "elevated", "text", "muted"].map((key) =>
					code(theme.colors[key] ?? "default"),
				),
			]),
		),
		`Semantic colour roles: ${Object.keys(colors.roles).length} roles in \`apps/web/src/styles/colors.json\`, e.g. ${Object.keys(
			colors.roles,
		)
			.slice(0, 8)
			.map(code)
			.join(", ")}. Transparency uses one alpha scale: ${Object.entries(colors.scale)
			.map(([step, percent]) => `${code(step)} ${percent}%`)
			.join(", ")}.`,
		"### Typography",
		table(
			["Family", "Stack"],
			families.map(([id, family]) => [code(id), family.stack.join(", ")]),
		),
		table(
			["Class", "Family", "Size", "Weight", "Line height", "Alias of"],
			styles.map((entry) => [
				code(`.${styleClassName(t, entry.group, entry.name)}`),
				entry.style.fontFamily,
				`${t.fontSizes[entry.style.fontSize]}px`,
				String(t.fontWeights[entry.style.fontWeight]),
				String(t.lineHeights[entry.style.lineHeight]),
				entry.ref ? code(entry.ref) : "—",
			]),
		),
		"### Spacing and radius",
		`Spacing steps (the step name is its pixel value): ${Object.keys(spacing.steps).map(code).join(" · ")}.`,
		`Radius steps: ${radiusSteps(read("apps/web/src/styles/tokens.css"))
			.map((step) => `${code(step.name.replace("--radius-", "rounded-"))} ${step.value}`)
			.join(" · ")}.`,
		"### Components",
		table(
			["Component", "Import", "Variants", "Sizes"],
			components.map((doc) => [
				doc.name,
				code(doc.importLine),
				Object.keys(doc.variants).map(code).join(", "),
				Object.keys(doc.sizes).map(code).join(", "),
			]),
		),
	].join("\n\n");
	return `${portable(body, DESIGN_PATH)}\n`;
}

export function renderOutputs(): Map<string, string> {
	const outputs = new Map<string, string>([
		[COMPONENTS_PATH, componentsMarkdown()],
		[DESIGN_PATH, designMarkdown()],
	]);
	for (const page of docs) {
		if (page.output) outputs.set(page.output.path, pageMarkdown({ ...page, output: page.output }));
	}
	return outputs;
}

if (import.meta.main) {
	const check = process.argv.includes("--check");
	const stale: string[] = [];
	for (const [path, next] of renderOutputs()) {
		const target = join(REPO, path);
		const current = existsSync(target) ? readFileSync(target, "utf8") : "";
		if (current === next) continue;
		if (check) stale.push(path);
		else {
			writeFileSync(target, next);
			console.log(`library: wrote ${path}`);
		}
	}
	if (stale.length > 0) {
		console.error(`library: stale generated docs — run ${COMMAND}:\n${stale.join("\n")}`);
		process.exit(1);
	}
	if (check) console.log("library: generated docs are up to date");
}
